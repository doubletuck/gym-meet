-- One row per manifest imported, so what is in the database can be checked
-- against the files under data/. Kept when its event is deleted.

create table import_run (
    id                    bigint generated by default as identity primary key,
    manifest              varchar(150) not null,
    event_id              bigint,
    discipline_code       varchar(3) not null,
    age_category_code     varchar(10) not null,
    content_hash          varchar(64) not null,
    replaced              boolean not null,
    warning_count         integer not null,
    report                text not null,
    creation_timestamp    timestamp(6) with time zone not null,
    last_update_timestamp timestamp(6) with time zone not null,
    constraint fk_import_run_event foreign key (event_id) references event (id) on delete set null
);

create index ix_import_run_manifest on import_run (manifest);
