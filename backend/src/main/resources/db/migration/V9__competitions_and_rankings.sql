-- Splits what a session was into what happened and how it was ranked (competition-models.md §7):
-- a competition holds routines (scores) and judges; a ranking orders one or more competitions'
-- results for a purpose, and team, all-around and apparatus results belong to a ranking. Teams
-- become rows, and how a score counted for a team is recorded per team result.
--
-- The result tables are rebuilt rather than converted: every row in them, and every participant,
-- comes from the import files, which are imported again after this migration (participants too,
-- since an import enters them afresh). Events, athletes, their name variants and clubs are kept,
-- and the re-import matches athletes to them again.

drop table judge;
drop table team_result;
drop table all_around_result;
drop table apparatus_result;
drop table score;
drop table session;
delete from participant;
delete from import_run;

create table competition (
    id                    bigint generated by default as identity primary key,
    event_id              bigint not null,
    competition_date      date not null,
    type_code             varchar(2) not null,
    discipline_code       varchar(3) not null,
    age_category_code     varchar(10) not null,
    apparatus_code        varchar(5),
    round                 integer,
    part                  integer,
    creation_timestamp    timestamp(6) with time zone not null,
    last_update_timestamp timestamp(6) with time zone not null,
    constraint uk_competition unique nulls not distinct (event_id, type_code, discipline_code, age_category_code, apparatus_code, round, part),
    constraint fk_competition_event foreign key (event_id) references event (id)
);

create table judge (
    id                    bigint generated by default as identity primary key,
    competition_id        bigint not null,
    apparatus_code        varchar(5),
    function_code         varchar(20) not null,
    given_name            varchar(60) not null,
    surname               varchar(60) not null,
    noc_code              varchar(10),
    creation_timestamp    timestamp(6) with time zone not null,
    last_update_timestamp timestamp(6) with time zone not null,
    constraint uk_judge unique nulls not distinct (competition_id, apparatus_code, function_code, surname, given_name),
    constraint fk_judge_competition foreign key (competition_id) references competition (id)
);

create table score (
    id                        bigint generated by default as identity primary key,
    participant_id            bigint not null,
    competition_id            bigint not null,
    apparatus_code            varchar(5) not null,
    difficulty                double precision,
    difficulty_inquiry        boolean not null,
    execution                 double precision,
    bonus                     double precision,
    bonus_detail              json,
    penalty                   double precision,
    sj_penalty                double precision,
    score                     double precision,
    status_code               varchar(20) not null,
    second_difficulty         double precision,
    second_difficulty_inquiry boolean,
    second_execution          double precision,
    second_bonus              double precision,
    second_bonus_detail       json,
    second_penalty            double precision,
    second_sj_penalty         double precision,
    second_score              double precision,
    second_status_code        varchar(20),
    combined_bonus            double precision,
    combined_sj_penalty       double precision,
    total_score               double precision,
    creation_timestamp        timestamp(6) with time zone not null,
    last_update_timestamp     timestamp(6) with time zone not null,
    constraint uk_score unique (participant_id, competition_id, apparatus_code),
    constraint fk_score_participant foreign key (participant_id) references participant (id),
    constraint fk_score_competition foreign key (competition_id) references competition (id)
);

create index ix_score_competition on score (competition_id);

create table team (
    id                    bigint generated by default as identity primary key,
    event_id              bigint not null,
    discipline_code       varchar(3) not null,
    age_category_code     varchar(10) not null,
    name                  varchar(100) not null,
    noc                   varchar(4),
    creation_timestamp    timestamp(6) with time zone not null,
    last_update_timestamp timestamp(6) with time zone not null,
    constraint uk_team unique (event_id, discipline_code, age_category_code, name),
    constraint fk_team_event foreign key (event_id) references event (id)
);

create table ranking (
    id                    bigint generated by default as identity primary key,
    event_id              bigint not null,
    discipline_code       varchar(3) not null,
    age_category_code     varchar(10) not null,
    type_code             varchar(10) not null,
    apparatus_code        varchar(5),
    purpose_code          varchar(20) not null,
    creation_timestamp    timestamp(6) with time zone not null,
    last_update_timestamp timestamp(6) with time zone not null,
    constraint fk_ranking_event foreign key (event_id) references event (id)
);

create index ix_ranking_event on ranking (event_id);

create table ranking_competition (
    ranking_id     bigint not null,
    competition_id bigint not null,
    constraint pk_ranking_competition primary key (ranking_id, competition_id),
    constraint fk_ranking_competition_ranking foreign key (ranking_id) references ranking (id),
    constraint fk_ranking_competition_competition foreign key (competition_id) references competition (id)
);

create index ix_ranking_competition_competition on ranking_competition (competition_id);

create table team_result (
    id                        bigint generated by default as identity primary key,
    ranking_id                bigint not null,
    team_id                   bigint not null,
    total_score               double precision,
    sj_penalty                double precision,
    rank                      integer,
    rank_status_code          varchar(20),
    qualification_result_code varchar(10),
    creation_timestamp        timestamp(6) with time zone not null,
    last_update_timestamp     timestamp(6) with time zone not null,
    constraint uk_team_result unique (ranking_id, team_id),
    constraint fk_team_result_ranking foreign key (ranking_id) references ranking (id),
    constraint fk_team_result_team foreign key (team_id) references team (id)
);

create index ix_team_result_team on team_result (team_id);

create table all_around_result (
    id                        bigint generated by default as identity primary key,
    ranking_id                bigint not null,
    participant_id            bigint not null,
    total_score               double precision,
    sj_penalty                double precision,
    rank                      integer,
    rank_status_code          varchar(20),
    qualification_result_code varchar(10),
    creation_timestamp        timestamp(6) with time zone not null,
    last_update_timestamp     timestamp(6) with time zone not null,
    constraint uk_all_around_result unique (ranking_id, participant_id),
    constraint fk_all_around_result_ranking foreign key (ranking_id) references ranking (id),
    constraint fk_all_around_result_participant foreign key (participant_id) references participant (id)
);

create index ix_all_around_result_participant on all_around_result (participant_id);

create table apparatus_result (
    id                        bigint generated by default as identity primary key,
    ranking_id                bigint not null,
    participant_id            bigint not null,
    total_score               double precision,
    rank                      integer,
    rank_status_code          varchar(20),
    qualification_result_code varchar(10),
    creation_timestamp        timestamp(6) with time zone not null,
    last_update_timestamp     timestamp(6) with time zone not null,
    constraint uk_apparatus_result unique (ranking_id, participant_id),
    constraint fk_apparatus_result_ranking foreign key (ranking_id) references ranking (id),
    constraint fk_apparatus_result_participant foreign key (participant_id) references participant (id)
);

create index ix_apparatus_result_participant on apparatus_result (participant_id);

create table team_result_score (
    team_result_id bigint not null,
    score_id       bigint not null,
    role_code      varchar(20) not null,
    constraint pk_team_result_score primary key (team_result_id, score_id),
    constraint fk_team_result_score_team_result foreign key (team_result_id) references team_result (id),
    constraint fk_team_result_score_score foreign key (score_id) references score (id)
);

create index ix_team_result_score_score on team_result_score (score_id);
