-- Where each title was decided, per event, discipline and age category (competition-models.md
-- §7.2, point 3): in Competition I (C1), in the title's own final (FINAL), or not held (NONE).
-- Filled from the import manifests, so it starts empty and is filled by importing again.

create table event_format (
    id                    bigint generated by default as identity primary key,
    event_id              bigint not null,
    discipline_code       varchar(3) not null,
    age_category_code     varchar(10) not null,
    team_format_code      varchar(10) not null,
    aa_format_code        varchar(10) not null,
    apparatus_format_code varchar(10) not null,
    creation_timestamp    timestamp(6) with time zone not null,
    last_update_timestamp timestamp(6) with time zone not null,
    constraint uk_event_format unique (event_id, discipline_code, age_category_code),
    constraint fk_event_format_event foreign key (event_id) references event (id)
);
